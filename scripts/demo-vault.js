#!/usr/bin/env node
/*
 * Builds a demo vault with goals, one-off and recurring tasks and occurrence pages,
 * dated relative to today, with Recurra installed (no sync accounts connected).
 *
 *   node scripts/demo-vault.js [target-folder]      (default: ./demo-vault)
 *   node scripts/demo-vault.js <your vault> --tasks-only --tasks TaskManager/Tasks --goals TaskManager/Goals
 *
 * Full mode: then in Obsidian "Open folder as vault" → the target folder → trust the author.
 * --tasks-only: only adds demo tasks (marked `demo: true`) to an existing vault and links them
 *   to its goals with the same names; no plugin, settings, goals or view notes are written.
 * Used for the README screenshots.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const args = process.argv.slice(2);
const opt = (name, dflt) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : dflt; };
const positional = args.filter((a, i) => !a.startsWith('--') && !(i > 0 && ['--tasks', '--goals'].includes(args[i - 1])));
const root = path.resolve(positional[0] || 'demo-vault');
const tasksOnly = args.includes('--tasks-only');
const TASKS = opt('--tasks', 'Tasks');
const GOALS = opt('--goals', 'Goals');
const repo = path.resolve(__dirname, '..');

const pad = (n) => String(n).padStart(2, '0');
const ymd = (d) => `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
const today = new Date(); today.setHours(0, 0, 0, 0);
const day = (n) => { const d = new Date(today); d.setDate(d.getDate() + n); return d; };
const D = (n) => ymd(day(n));
const monthStart = (m) => ymd(new Date(today.getFullYear(), today.getMonth() + m, 1));
const monthEnd = (m) => ymd(new Date(today.getFullYear(), today.getMonth() + m + 1, 0));

function write(rel, text) {
  const p = path.join(root, rel);
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, text.replace(/^\n/, ''));
}
const yamlList = (xs) => `[${xs.join(', ')}]`;
/** In --tasks-only mode, link to the vault's own goal note whose name matches (ignoring spacing). */
function goal(name) {
  if (!tasksOnly) return `"[[${name}]]"`;
  const dir = path.join(root, GOALS);
  const norm = (x) => x.replace(/\s+/g, ' ').trim();
  const hit = fs.existsSync(dir) && fs.readdirSync(dir).map((f) => f.replace(/\.md$/, '')).find((f) => norm(f) === norm(name));
  return hit ? `"[[${hit}]]"` : '';
}
function note(fm, body) {
  if (tasksOnly && fm.type === 'task') fm = Object.assign({}, fm, { demo: true });
  const lines = ['---'];
  for (const [k, v] of Object.entries(fm)) lines.push(`${k}: ${Array.isArray(v) ? yamlList(v) : v}`);
  lines.push('---', '', body || '');
  return lines.join('\n');
}
/** past occurrence dates of a weekday-set series, starting `from` days ago up to yesterday */
function pastDays(from, weekdays) {
  const out = [];
  for (let i = -from; i < 0; i++) if (!weekdays || weekdays.includes(day(i).getDay())) out.push(D(i));
  return out;
}

if (tasksOnly) {
  if (!fs.existsSync(path.join(root, '.obsidian'))) { console.error(`${root} is not an Obsidian vault.`); process.exit(1); }
  const clash = ['LeetCode', 'Gym', 'Update CV'].find((n) => fs.existsSync(path.join(root, TASKS, `${n}.md`)));
  if (clash) { console.error(`${TASKS}/${clash}.md already exists; not overwriting your notes.`); process.exit(1); }
} else {
  if (fs.existsSync(root) && fs.readdirSync(root).length && !fs.existsSync(path.join(root, '.recurra-demo'))) {
    console.error(`${root} exists and is not a Recurra demo vault; pick an empty folder.`);
    process.exit(1);
  }
  fs.mkdirSync(root, { recursive: true });
  fs.writeFileSync(path.join(root, '.recurra-demo'), 'generated by scripts/demo-vault.js\n');
}

if (!tasksOnly) {
// ---- plugin -------------------------------------------------------------------------------
const plug = path.join(root, '.obsidian/plugins/recurra');
fs.mkdirSync(plug, { recursive: true });
for (const f of ['main.js', 'manifest.json', 'styles.css']) fs.copyFileSync(path.join(repo, f), path.join(plug, f));
fs.writeFileSync(path.join(plug, 'data.json'), JSON.stringify({ settings: { tasksFolder: 'Tasks', goalsFolder: 'Goals', defaultReminder: 'at start' } }, null, 2));
write('.obsidian/community-plugins.json', JSON.stringify(['recurra']));
write('.obsidian/app.json', JSON.stringify({ propertiesInDocument: 'hidden' }, null, 2));
write('.obsidian/appearance.json', JSON.stringify({ theme: 'obsidian' }, null, 2));

// ---- goals ----------------------------------------------------------------------------------
write('Goals/Career Change 💼.md', note({ type: 'goal', target_start: monthStart(-3), target_end: monthEnd(7), description: '"Move from web dev to systems programming"' }));
write('Goals/Review topics.md', note({ type: 'goal', target_start: D(-75), target_end: monthEnd(1), parent_goal: goal('Career Change 💼') }));
write('Goals/Rust 🦀.md', note({ type: 'goal', target_start: D(5), target_end: monthEnd(5), parent_goal: goal('Career Change 💼') }));
write('Goals/Italian 🇮🇹.md', note({ type: 'goal', target_start: monthStart(-2), target_end: monthEnd(1) }));
write('Goals/Italian Exam A2 🇮🇹.md', note({ type: 'goal', target_start: D(10), target_end: monthEnd(1), parent_goal: goal('Italian 🇮🇹') }));
write('Goals/Driving License 🚘.md', note({ type: 'goal', target_start: monthStart(2), target_end: D(120) }));
}

// ---- recurring tasks --------------------------------------------------------------------------
const weekdays = [1, 2, 3, 4, 5];
const lcPast = pastDays(21, weekdays);
const lcSkipped = lcPast.slice(-6, -5);
const lcMoved = lcPast.slice(-4, -3);
const lcDone = lcPast.filter((d) => !lcSkipped.includes(d) && !lcMoved.includes(d) && d !== lcPast[lcPast.length - 8]);
write(`${TASKS}/LeetCode.md`, note({
  type: 'task', goal: goal('Review topics'), time: `${lcPast[0] || D(0)}T08:00`, duration: 45,
  recurring: '"every weekday"', reminder: '10m',
  done_dates: lcDone, skipped_dates: lcSkipped, moved: lcMoved.map((d) => `"${d} -> ${d}T20:30"`),
}, '```task-occurrences\n```\n'));

const page = (task, date, body) => write(`${TASKS}/${task}/${task} ${date}.md`,
  note({ type: 'occurrence', series: `"[[${task}]]"`, date }, '```task-occurrence\n```\n\n' + body));
const lastWeekday = lcPast.filter((d) => !lcSkipped.includes(d)).slice(-1)[0];
page('LeetCode', D(0), `## Plan
- [ ] 1143. Longest Common Subsequence (DP, medium)
- [ ] Re-do 300. Longest Increasing Subsequence without notes

## Notes
Tabulation first, then squeeze the table to two rows → O(min(m, n)) memory.
`);
if (lastWeekday) page('LeetCode', lastWeekday, `## Solved
- [x] 200. Number of Islands: BFS, then union-find for comparison
- [x] 994. Rotting Oranges: multi-source BFS

## Takeaways
Multi-source BFS = push every source at distance 0, then run the normal loop.
Related: [[Rust 🦀]] (try the same in Rust with \`VecDeque\`).
`);

const mwf = [1, 3, 5];
write(`${TASKS}/Rust book chapter.md`, note({
  type: 'task', goal: goal('Rust 🦀'), time: `${D(-14)}T19:00`, duration: '1h', recurring: '"every Mon, Wed, Fri"',
  reminder: yamlList(['1h', '10m']), done_dates: pastDays(14, mwf).slice(0, -1), skipped_dates: [], moved: [],
}, '```task-occurrences\n```\n'));

const tt = [2, 4];
const itPast = pastDays(28, tt);
const nextIt = [1, 2, 3, 4, 5, 6, 7].map((n) => D(n)).find((d) => tt.includes(new Date(d + 'T00:00').getDay()));
write(`${TASKS}/Italian lesson.md`, note({
  type: 'task', goal: goal('Italian Exam A2 🇮🇹'), time: `${itPast[0] || D(0)}T18:00`, duration: 90, recurring: '"every Tue, Thu"',
  reminder: '30m', done_dates: itPast, skipped_dates: [], moved: nextIt ? [`"${nextIt} -> ${nextIt}T10:00"`] : [],
}, '```task-occurrences\n```\n'));

write(`${TASKS}/Gym.md`, note({
  type: 'task', time: `${D(-12)}T07:00`, duration: 60, recurring: '"every 2 days"', reminder: '15m',
  done_dates: [D(-12), D(-10), D(-6), D(-4)], skipped_dates: [D(-8)], moved: [],
}, '```task-occurrences\n```\n'));

write(`${TASKS}/Monthly review.md`, note({
  type: 'task', goal: goal('Career Change 💼'), time: `${monthStart(-2)}T17:00`, duration: 30,
  recurring: '"every month on the last Fri"', reminder: '1d', done_dates: [], skipped_dates: [], moved: [],
}, '```task-occurrences\n```\n'));

// ---- one-off tasks ------------------------------------------------------------------------------
write(`${TASKS}/Update CV.md`, note({ type: 'task', goal: goal('Career Change 💼'), time: `${D(0)}T09:30`, duration: 45, status: 'Done' }));
write(`${TASKS}/Book driving theory test.md`, note({ type: 'task', goal: goal('Driving License 🚘'), time: `${D(0)}T11:00`, duration: 20, status: '"In progress"', reminder: '10m' }));
write(`${TASKS}/Reply to recruiter.md`, note({ type: 'task', goal: goal('Career Change 💼'), time: `${D(0)}T14:00`, duration: 15, status: '"Not started"' }));
write(`${TASKS}/Submit A2 exam registration.md`, note({ type: 'task', goal: goal('Italian Exam A2 🇮🇹'), time: D(-1), status: '"Not started"', reminder: '3h' }));
write(`${TASKS}/Renew passport.md`, note({ type: 'task', time: `${D(2)}T10:00`, duration: 60, status: '"Not started"', reminder: yamlList(['1d', '1h']) }));
write(`${TASKS}/Call driving school.md`, note({ type: 'task', goal: goal('Driving License 🚘'), time: D(4), status: '"Not started"' }));

// ---- view notes -------------------------------------------------------------------------------
if (!tasksOnly) {
write('Today.md', '```task-today\n```\n\n```task-upcoming\n```\n');
write('Week.md', '```task-week\n```\n');
write('Goals.md', '```goal-timeline\n```\n');
write('Welcome.md', `# Recurra demo vault

Generated ${D(0)} by \`scripts/demo-vault.js\`. Sync is not connected.

- [[Today]]: today's tasks, overdue and upcoming
- [[Week]]: this week
- [[Goals]]: goal timeline
- [[LeetCode]]: a recurring task with its occurrence list
`);
}

console.log(tasksOnly ? `Demo tasks added to ${path.join(root, TASKS)} (marked demo: true)` : `Demo vault written to ${root}`);
